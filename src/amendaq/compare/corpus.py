def iter_faqs() -> list[dict]:
    rows: list[dict] = []
    for chapter in CHAPTERS:
        for item in chapter["faqs"]:
            rows.append({**item, "chapter": chapter["title"]})
    return rows


def render_source() -> str:
    parts = [TITLE, ""]
    index = 1
    for chapter in CHAPTERS:
        paragraphs = [p.strip() for p in chapter["paragraphs"] if p.strip()]
        if not paragraphs:
            continue
        parts.append(f"{index}. {chapter['title']}")
        parts.append("")
        parts.extend(paragraphs)
        parts.append("")
        index += 1
    return "\n".join(parts).strip() + "\n"


def render_faq() -> str:
    lines: list[str] = []
    number = 1
    for item in iter_faqs():
        lines.append(f"Q{number}：{item['q']}")
        lines.append(f"A{number}：{item['a']}")
        lines.append("")
        number += 1
    return "\n".join(lines).strip() + "\n"


def faq_only_answers() -> list[str]:
    return [item["a"] for item in iter_faqs() if item.get("faq_only")]


